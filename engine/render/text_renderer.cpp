struct Tvtx { float pos[3]; float col[4]; };

bool TextRenderer::init(ID3D11Device* device, int sw, int sh) {
    device_ = device; sw_ = sw; sh_ = sh;
    device->GetImmediateContext(&ctx_);

    // shaders compiled from memory
    const char* vsSrc =
        "cbuffer CB : register(b0){ float4x4 proj; }"
        "struct VI { float2 p : POS; float4 c : COL; };"
        "struct VO { float4 pos : SV_POSITION; float4 c : COL; };"
        "VO main(VI i){ VO o; o.pos = mul(proj, float4(i.p,0,1)); o.c = i.c; return o; }";
    const char* psSrc =
        "struct PI { float4 pos : SV_POSITION; float4 c : COL; };"
        "float4 main(PI i) : SV_Target { return i.c; }";

    ID3DBlob *vsb = nullptr, *psb = nullptr, *err = nullptr;
    if (FAILED(D3DCompile(vsSrc, strlen(vsSrc), nullptr, nullptr, nullptr,
                          "main", "vs_5_0", 0, 0, &vsb, &err))) return false;
    if (FAILED(device->CreateVertexShader(vsb->GetBufferPointer(), vsb->GetBufferSize(),
                                          nullptr, &vs_))) return false;
    if (FAILED(D3DCompile(psSrc, strlen(psSrc), nullptr, nullptr, nullptr,
                          "main", "ps_5_0", 0, 0, &psb, &err))) return false;
    if (FAILED(device->CreatePixelShader(psb->GetBufferPointer(), psb->GetBufferSize(),
                                         nullptr, &ps_))) return false;

    D3D11_INPUT_ELEMENT_DESC layout[] = {
        { "POS", 0, DXGI_FORMAT_R32G32_FLOAT, 0, 0, D3D11_INPUT_PER_VERTEX_DATA, 0 },
        { "COL", 0, DXGI_FORMAT_R32G32B32A32_FLOAT, 0, 8, D3D11_INPUT_PER_VERTEX_DATA, 0 },
    };
    if (FAILED(device->CreateInputLayout(layout, 2, vsb->GetBufferPointer(),
                                         vsb->GetBufferSize(), &il_))) return false;
    vsb->Release(); psb->Release();

    // dynamic vertex buffer: up to ~2048 quads
    D3D11_BUFFER_DESC bd{};
    bd.Usage = D3D11_USAGE_DYNAMIC;
    bd.ByteWidth = sizeof(Tvtx) * 2048 * 4;
    bd.BindFlags = D3D11_BIND_VERTEX_BUFFER;
    bd.CPUAccessFlags = D3D11_CPU_ACCESS_WRITE;
    if (FAILED(device->CreateBuffer(&bd, nullptr, &vb_))) return false;

    // ortho projection cbuffer
    bd.Usage = D3D11_USAGE_DEFAULT;
    bd.ByteWidth = 64; bd.BindFlags = D3D11_BIND_CONSTANT_BUFFER;
    bd.CPUAccessFlags = 0;
    if (FAILED(device->CreateBuffer(&bd, nullptr, &cb_))) return false;

    updateProj();
    return true;
}

void TextRenderer::updateProj() {
    float L = 0, R = (float)sw_, T = 0, B = (float)sh_;
    float m[16] = {
        2/(R-L), 0, 0, 0,
        0, -2/(T-B), 0, 0,
        0, 0, 1, 0,
        -(R+L)/(R-L), -(T+B)/(T-B), 0, 1
    };
    ctx_->UpdateSubresource(cb_, 0, nullptr, m, 0, 0);
}

void TextRenderer::resize(int w, int h) {
    sw_ = w; sh_ = h;
    updateProj();
}

void TextRenderer::shutdown() {
    if (vb_) vb_->Release();
    if (cb_) cb_->Release();
    if (il_) il_->Release();
    if (vs_) vs_->Release();
    if (ps_) ps_->Release();
    vb_=nullptr; cb_=nullptr; il_=nullptr; vs_=nullptr; ps_=nullptr;
}

void TextRenderer::draw(const std::string& text, float x, float y, float scale,
                        float r, float g, float b) {
    if (!ctx_) return;
    Tvtx verts[2048*4];
    int n = 0;
    float cx = x, cy = y;
    for (char ch : text) {
        if (ch == '\n') { cx = x; cy += 9*scale; continue; }
        if ((size_t)n + 4 > 2048*4) break;
        int gi = (unsigned char)ch - 32;
        if (gi < 0 || gi >= 95) gi = 0;
        for (int row = 0; row < 7; ++row) {
            uint16_t bits = kFont[gi][row];
            for (int col = 0; col < 5; ++col) {
                if (!((bits >> (4-col)) & 1)) continue;
                float px = cx + col*scale, py = cy + row*scale;
                float qx = px + scale, qy = py + scale;
                Tvtx quad[6] = {
                    { px,py,0, r,g,b,1 }, { qx,py,0, r,g,b,1 }, { qx,qy,0, r,g,b,1 },
                    { px,py,0, r,g,b,1 }, { qx,qy,0, r,g,b,1 }, { px,qy,0, r,g,b,1 },
                };
                if ((size_t)n + 6 > 2048*4) break;
                memcpy(&verts[n], quad, sizeof(quad));
                n += 6;
            }
        }
        cx += 6*scale;
    }
    if (!n) return;

    D3D11_MAPPED_SUBRESOURCE map;
    if (FAILED(ctx_->Map(vb_, 0, D3D11_MAP_WRITE_DISCARD, 0, &map))) return;
    memcpy(map.pData, verts, sizeof(Tvtx) * n);
    ctx_->Unmap(vb_, 0);

    UINT stride = sizeof(Tvtx), off = 0;
    ctx_->IASetInputLayout(il_);
    ctx_->IASetVertexBuffers(0, 1, &vb_, &stride, &off);
    ctx_->IASetPrimitiveTopology(D3D11_PRIMITIVE_TOPOLOGY_TRIANGLELIST);
    ctx_->VSSetShader(vs_, nullptr, 0);
    ctx_->PSSetShader(ps_, nullptr, 0);
    ctx_->VSSetConstantBuffers(0, 1, &cb_);
    ctx_->Draw(n, 0);
}

